def last_attempt(sub):
    return sub['attempts'][-1]['prompt']

def run_id(path, kind):
    t = open(path, encoding='utf-8').read()
    if kind == 'sma-c':
        m = re.search(r'"audit_run_id": "([^"]+)"', t)
    elif kind == 'analyzer-phase1':
        m = re.search(r'Запуск фазы: (\S+)\.', t)
    else:
        m = re.search(r'Запуск анализа: (\S+)\.', t)
    if not m:
        raise SystemExit('no run id in ' + path)
    return m.group(1)

def write(path, obj):
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, 'w', encoding='utf-8') as fh:
        json.dump(obj, fh, ensure_ascii=False, indent=2)
        fh.write('\n')
    print('WROTE', os.path.relpath(path, ROOT))

def main():
    ledger = json.load(open(LEDGER, encoding='utf-8'))
    task = [t for t in ledger['tasks'] if t['id'] == 'T-0062'][0]
    subs = {s['id']: s for s in task['subtasks']}
    for ch, (c_id, p1_id, p2_id) in CH_IDS.items():
        c_run = run_id(last_attempt(subs[c_id]), 'sma-c')
        p1_run = run_id(last_attempt(subs[p1_id]), 'analyzer-phase1')
        findings = F[ch]
        cdoc = dict(audit_id='sma-c', audit_type='pragmatic-audit',
                    audit_run_id=c_run, chapter=ch, findings=findings,
                    coverage=COV[ch])
        write(f'{BASE}/{ch}/c/{c_run}.json', cdoc)

        results = []
        for f in findings:
            results.append(dict(block=f['block'], finding='PRAGMATIC_SHIFT',
                                note=f['aspect'] + ': ' + f['reason'],
                                confidence=f['confidence']))
        seen = {r['block'] for r in results}
        maxblk = max(seen) if seen else 1
        for b in range(1, maxblk + 1):
            if b not in seen:
                results.append(dict(block=b, finding='NONE',
                                    note='Существенного прагматического расхождения не найдено.',
                                    confidence='HIGH'))
        results.sort(key=lambda r: r['block'])
        pdoc = dict(analysis_id=p1_run + '.phase1', chapter=ch, phase=1,
                    scope='blind', results=results)
        write(f'{BASE}/{ch}/analysis/{p1_run}.phase1.json', pdoc)
        print(f'  {ch}: C={c_run} phase1={p1_run} findings={len(findings)}')

if __name__ == '__main__':
    main()
