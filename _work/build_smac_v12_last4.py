def write_json(path, obj):
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, "w", encoding="utf-8", newline="\n") as h:
        json.dump(obj, h, ensure_ascii=False, indent=2)
        h.write("\n")


def write_md(path, d, chapter, ph2_id):
    res = d["phase2"]
    from collections import Counter
    sc = Counter(x["status"] for x in res)
    ac = Counter(x["action"] for x in res)
    lines = [
        f"# Analyzer — Фаза 2: v12-{chapter}", "",
        f"- analysis_id: `{ph2_id}`",
        "- Режим: A + B + C; правки текста **не вносились** (action FIXED = 0).",
        f"- inputs.phase1: `{d['ph1_id']}.phase1.json` (новый слепой вывод этого раунда)",
        "- a_runs: " + ", ".join(d["a_runs"]),
        "- b_runs: " + ", ".join(d["b_runs"]),
        "- c_runs: " + ", ".join(d["c_runs"]),
        f"- precheck: `{d['precheck']}`",
        f"- Итого кандидатов: {len(res)}; статусы: {dict(sc)}; действия: {dict(ac)}",
        "",
        "| block | candidate_id | sources (A/B/C) | fidelity | status | action | reason |",
        "| --- | --- | --- | --- | --- | --- | --- |",
    ]
    for x in res:
        s = x["sources"]
        src = "A:" + ",".join(s["a"]) if s["a"] else "A:-"
        src += " B:" + (",".join(s["b"]) if s["b"] else "-")
        src += " C:" + (",".join(s["c"]) if s["c"] else "-")
        src += " pc:" + ("yes" if s["precheck"] else "net")
        reason = x["reason"].replace("|", "/").replace("\n", " ")
        if len(reason) > 220:
            reason = reason[:220] + "..."
        lines.append(
            f"| {x['block']} | {x['candidate_id']} | {src} | {x['fidelity']} | "
            f"{x['status']} | {x['action']} | {reason} |")
    for title, key in (("DISPUTED", "DISPUTED"), ("FALSE_POSITIVE", "FALSE_POSITIVE")):
        subset = [x for x in res if x["status"] == key]
        if subset:
            lines += ["", f"## {title} ({len(subset)})", ""]
            for x in subset:
                lines.append(f"- бл. {x['block']} ({x['candidate_id']}): {x['reason']} "
                             f"— {x['action']}, текст сохранён.")
    reports = [x for x in res if x["action"] == "REPORT_ONLY"]
    if reports:
        lines += ["", f"## REPORT_ONLY ({len(reports)})", ""]
        for x in reports:
            lines.append(f"- бл. {x['block']} ({x['candidate_id']}): "
                         f"{x['status']} / {x['fidelity']}. "
                         f"Предложение: {x['suggestion']}")
    lines += ["", "## Две оси решения", "",
              "Каждому кандидату назначены fidelity (MEANING_SHIFT / COMPONENT_LOSS / "
              "ADDITION / MISSING / RUSSIAN_ERROR / FORMAT) и action/status "
              "(CONFIRMED_ERROR / DISPUTED / FALSE_POSITIVE; FIXED / REPORT_ONLY / "
              "PRESERVED). Majority vote не применялся: решение принято по паре JA → RU. "
              "FIXED не используется — в этом раунде текст не правится."]
    with open(path, "w", encoding="utf-8", newline="\n") as h:
        h.write("\n".join(lines) + "\n")


def check_quotes(chapter, d):
    """Verify new C finding quotes are exact substrings of JA / current RU."""
    def blocks(path):
        t = open(path, encoding="utf-8").read()
        parts = re.split(r"<!-- block: (\d+) -->", t)
        return {int(parts[i]): parts[i + 1].strip()
                for i in range(1, len(parts), 2)}
    ja = blocks(f"{SRC}/translates/ja/v12-{chapter}.md")
    ru = blocks(f"{SRC}/output/chapters/v12-{chapter}.md")
    ok = True
    for x in d["findings"]:
        b = x["block"]
        for field, col in (("source", ja), ("current", ru)):
            quote = x[field]
            hit = any(quote in text for text in col.values())
            if not hit:
                # try all blocks joined (RU may shift by one)
                hit = quote in "\n".join(col.values())
            if not hit:
                print(f"  !! {chapter} block {b} {field}: НЕ НАЙДЕНО: {quote[:70]}")
                ok = False
    return ok


