# -*- coding: utf-8 -*-
"""Дозапись записей аудита в output/_log/v4-log.md через save_block.py (stdin)."""
import subprocess
import sys
from pathlib import Path

if sys.stdout.encoding and sys.stdout.encoding.lower() != "utf-8":
    sys.stdout.reconfigure(encoding="utf-8")

BASE = Path(__file__).resolve().parents[3]
SAVE = BASE / "scripts" / "save_block.py"

TEXT = """
## ch01 — ПОЛНЫЙ АУДИТ v04 (правки слоёв)

- ПРАВКА (ОФОРМЛЕНИЕ), б2: «...что стоял поблизости.» → «...что стоял
  поблизости:» — абзац перед репликой с глаголом речи (окликнул) заканчивается
  двоеточием (russian-prose-rules); в сырой RU двоеточие было.
- ПРАВКА (СТИЛЬ), б5: «Но впоследствии оказалось» → «Но впоследствии
  выяснилось» — «оказалось» дважды в абзаце (style_scan абз. 80).
- ПРАВКА (СТИЛЬ), б6: «чуть позже третьего дня» → «чуть позже трёх пополудни» —
  «третьего дня» устар. = «позавчера»; по JA 午後の三時過ぎ (после полудня).
- ПРАВКА (МАШИННОСТЬ), б8: «вещь, связанная руками» → «ручная работа» —
  калька с 手作り (translationese, russian-humanizer).
- ПРАВКА (СТИЛЬ), б8: «Сайто, пасуя,» → «Сайто, робея,» — «пасовать» не
  передаёт どぎまぎ (смущение); лексический диссонанс.
- ПРАВКА (ГРАММАТИКА/АКТАНТЫ), б9: «заставила вырыть яму крота Гиша» →
  «заставила крота Гиша вырыть яму» — снят сад-путь («яму крота Гиша»);
  по JA ギーシュのモグラに穴を掘らせ (кто → что делает → что).
- ПРАВКА (ОФОРМЛЕНИЕ), б10: «Дерфлингер спросил ровным, притворно-невинным
  голосом.» → «Дерфлингер сказал ровным, притворно-невинным голосом:» —
  JA 言った (сказал, не вопрос) + двоеточие перед репликой.
- ПРАВКА (ТЕРМИН), б12: «Недавний взрыв магического света» → «Недавний
  магический свет „Взрыв“» — в JA названо заклинание エクсプロージョン;
  канон главы «Взрыв» (б15).
- ПРАВКА (СТИЛЬ), б13: «в баню ходили» / «в баню заходили» → «в ванну...» —
  тот же случай в б15–б17 назван «ванной» (JA 風呂, сырой RU «ванну»);
  единообразие внутри главы.
- ПРАВКА (СМЫСЛ), б14: «— Следующий будет он, милый мой.» → «— Следующий
  будет он.» — «милый мой» в JA отсутствует (次はあいつだかんね), добавление.
- ПРАВКА (СТИЛЬ), б17: «нагнетённый электрический разряд» → «накопленный
  электрический разряд» — коллокация: разряд не «нагнетают» (JA 込められた).
- СОМНЕНИЕ, б13: JA 人間の男 («мужики-человеческие») передано как «мужики» —
  видовая метка опущена (EN тоже опускает); можно добавить «человеческие».
  Требует решения пользователя.
- НАБЛЮДЕНИЕ (JA ↔ EN), б9: JA デルфリンガーはいろいろと聞きたいことが
  あったので... — по JA вопросы были у меча; EN приписывает их Луизе
  («she had things she wanted to ask him»). Вывод оставлен по JA.
- НАБЛЮДЕНИЕ (JA ↔ EN), б15: JA そっと部屋から抜け出そうとした («стал
  ускользать из комнаты»); EN «slowly backed towards the door». Вывод ближе к
  EN («попятился к двери»), последовательность действий (движение к двери,
  попытка открыть) по JA сохранена — смысл не искажён.
"""


def main():
    # диагностика кодировки канала
    sample = TEXT[:40].encode("utf-8")
    # payload в файл (--text-file): кириллица не проходит через shell
    payload = Path(__file__).resolve().parent / "_log_payload.txt"
    with payload.open("w", encoding="utf-8", newline="\n") as fh:
        fh.write(TEXT)
    r = subprocess.run(
        [sys.executable, str(SAVE), "--file", "_log/v4-log.md",
         "--text-file", str(payload)],
        capture_output=True, text=True, encoding="utf-8",
        cwd=str(BASE))
    if r.returncode == 0:
        sys.stdout.write(r.stdout)
        return 0
    sys.stderr.write("save_block failed (%s); fallback: direct append\n"
                     % r.stderr.strip())
    sys.stderr.write("sample utf-8: %r\n" % sample)
    log = BASE / "output" / "_log" / "v4-log.md"
    with log.open("a", encoding="utf-8", newline="\n") as f:
        if not TEXT.startswith("\n"):
            f.write("\n")
        f.write(TEXT)
        if not TEXT.endswith("\n"):
            f.write("\n")
    print("OK: log appended directly -> %s" % log.name)
    return 0


if __name__ == "__main__":
    sys.exit(main())
