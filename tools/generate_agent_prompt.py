def clear_screen() -> None:
    """Очистить экран."""
    if sys.platform == "win32":
        os.system("cls")
    else:
        print("\033[2J\033[H", end="")


def read_key() -> str:
    """
    Прочитать одну клавишу.

    Возвращает:
        up
        down
        left
        right
        enter
        esc
        q
        other
    """
    key = msvcrt.getwch()

    # Стрелки и специальные клавиши Windows
    if key in ("\x00", "\xe0"):
        key = msvcrt.getwch()

        special_keys = {
            "H": "up",
            "P": "down",
            "K": "left",
            "M": "right",
        }

        return special_keys.get(key, "other")

    if key in ("\r", "\n"):
        return "enter"

    if key == "\x1b":
        return "esc"

    if key.lower() == "q":
        return "q"

    return "other"


def separator(char: str = "─", width: int = TERMINAL_WIDTH) -> None:
    """Вывести разделитель."""
    print(char * width)


def print_wrapped(
    text: str,
    width: int = TERMINAL_WIDTH,
    indent: str = "",
) -> None:
    """
    Вывести текст с автоматическим переносом строк.

    Пустые строки сохраняются.
    """
    if not text:
        print()
        return

    for line in text.splitlines():
        if not line.strip():
            print()
            continue

        wrapped = textwrap.wrap(
            line,
            width=max(20, width - len(indent)),
            break_long_words=False,
            break_on_hyphens=False,
        )

        if not wrapped:
            print()
            continue

        for part in wrapped:
            print(indent + part)


def terminal_width() -> int:
    """Получить ширину терминала."""
    try:
        return shutil.get_terminal_size((TERMINAL_WIDTH, 24)).columns
    except Exception:
        return TERMINAL_WIDTH


def select_option(
    options: list[tuple[str, str]],
    title: str = "",
    footer: str = (
        "↑ ↓ — выбор    Enter — подтвердить    Esc — отмена"
    ),
) -> int | None:
    """
    Интерактивный выбор пункта меню.

    options:
        [
            ("Название", "Краткое описание"),
            ...
        ]

    Возвращает индекс выбранного пункта.

    None = Esc / Q.
    """
    if not options:
        return None

    selected = 0
    width = terminal_width()

    while True:
        clear_screen()

        if title:
            print(title)
            separator(width=width)
            print()

        for index, (name, description) in enumerate(options):
            marker = "❯" if index == selected else " "

            print(f"{marker} {name}")

            # Описание каждого пункта меню тоже переносим.
            print_wrapped(
                description,
                width=width - 2,
                indent="  ",
            )

            print()

        separator(width=width)
        print(footer)

        key = read_key()

        if key == "up":
            selected = (selected - 1) % len(options)

        elif key == "down":
            selected = (selected + 1) % len(options)

        elif key == "enter":
            return selected

        elif key in {"esc", "q"}:
            return None


