def choose_prompt() -> int | str | None:
    """
    Возвращает:

        int       — индекс PROMPTS
        "change"  — изменить том/главу
        "quit"    — выход
    """

    options = [
        (
            prompt.title,
            prompt.description,
        )
        for prompt in PROMPTS
    ]

    options.append(
        (
            "Изменить том / главу",
            "Выбрать другой том и главу",
        )
    )

    options.append(
        (
            "Выход",
            "Закрыть генератор промптов",
        )
    )

    selected = select_option(
        options,
        title="AINovelEdit — генератор промптов",
        footer=(
            "↑ ↓ — выбор    "
            "Enter — подтвердить    "
            "Esc — выход    "
            "Q — выход"
        ),
    )

    if selected is None:
        return "quit"

    if selected < len(PROMPTS):
        return selected

    if selected == len(PROMPTS):
        return "change"

    return "quit"


