def ask_int(prompt: str, minimum: int = 1) -> int:
    """Запросить положительное целое число."""
    while True:
        try:
            value = int(input(prompt).strip())

            if value < minimum:
                raise ValueError

            return value

        except ValueError:
            print(
                f"  Введите целое число не меньше {minimum}."
            )


def ask_chapter() -> Chapter:
    """Выбрать том и главу."""
    print()
    print("Выбор главы")
    separator()
    print()

    volume = ask_int("Номер тома: ")
    chapter = ask_int("Номер главы: ")

    return Chapter(
        volume=volume,
        chapter=chapter,
    )


def ask_block_number() -> int:
    """Запросить номер блока."""
    return ask_int("Номер блока: ")


