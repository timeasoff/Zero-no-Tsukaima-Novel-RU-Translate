def copy_to_clipboard(text: str) -> bool:
    """
    Копирует Unicode-текст в буфер обмена Windows.
    Использует PowerShell и .NET напрямую, без передачи
    русского текста через кодировку консоли.
    """
    if sys.platform != "win32":
        return False

    try:
        # Передаём текст в PowerShell как Base64 UTF-8.
        # Благодаря этому кодировка консоли вообще не участвует.
        import base64

        encoded = base64.b64encode(text.encode("utf-8")).decode("ascii")

        command = (
            "$bytes = [Convert]::FromBase64String('"
            + encoded
            + "'); "
            "$text = [System.Text.Encoding]::UTF8.GetString($bytes); "
            "Set-Clipboard -Value $text"
        )

        process = subprocess.run(
            [
                "powershell.exe",
                "-NoProfile",
                "-NonInteractive",
                "-Command",
                command,
            ],
            capture_output=True,
            text=True,
            encoding="utf-8",
            errors="replace",
        )

        return process.returncode == 0

    except Exception:
        return False


