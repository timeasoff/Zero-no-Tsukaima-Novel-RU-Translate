def ask_confirmation(
    title: str,
    prompt: PromptInfo,
    ch: Chapter,
) -> bool:
    """
    Экран подтверждения запуска режима.

    ВАЖНО:
    Здесь намеренно выводятся:
    1. название режима;
    2. краткое описание;
    3. подробное описание;
    4. вопрос подтверждения.

    Описание больше не зависит от предыдущего экрана.
    """

    options = ["Да", "Нет"]
    selected = 0
    width = terminal_width()

    while True:
        clear_screen()

        print(title)
        separator(width=width)
        print()

        print(f"Режим: {prompt.title}")
        print(f"Глава: {ch.chapter_id_full}")
        print()

        # ------------------------------------------------------------
        # КРАТКОЕ ОПИСАНИЕ
        # ------------------------------------------------------------

        print("Кратко:")
        print_wrapped(
            prompt.description,
            width=width,
            indent="  ",
        )

        print()

        # ------------------------------------------------------------
        # ПОДРОБНОЕ ОПИСАНИЕ
        # ------------------------------------------------------------

        print("Что делает этот режим:")

        print_wrapped(
            prompt.guide,
            width=width,
            indent="  ",
        )

        print()
        separator(width=width)
        print()

        print(
            f'Запустить режим "{prompt.title}" '
            f"для {ch.chapter_id_full}?"
        )

        print()

        for index, option in enumerate(options):
            marker = "❯" if index == selected else " "
            print(f"{marker} {option}")

        print()
        separator(width=width)

        print(
            "↑ ↓ — выбор    "
            "Enter — подтвердить    "
            "Esc — отмена    "
            "Q — отмена"
        )

        key = read_key()

        if key == "up":
            selected = (selected - 1) % len(options)

        elif key == "down":
            selected = (selected + 1) % len(options)

        elif key == "enter":
            return selected == 0

        elif key in {"esc", "q"}:
            return False


